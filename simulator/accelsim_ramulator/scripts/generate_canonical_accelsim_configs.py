#!/usr/bin/env python3
"""Generate clean AccelSim configs for validated Ramulator2 pairings.

The normal matrix runner can still build a per-run config from the stock
SM80_A100 config plus inline overrides.  These generated files are the same
effective architecture configs, with duplicate GPGPU-Sim options collapsed, so
humans do not have to read stale A100 lines next to H100/A100-stack overrides.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parents[1]
DEFAULT_BASE = (
    WORKSPACE
    / "simulator"
    / "gpgpu-sim_distribution"
    / "configs"
    / "tested-cfgs"
    / "SM80_A100"
    / "gpgpusim.config"
)
OUT_DIR = ROOT / "configs" / "accelsim" / "canonical"
FRAGMENT_DIR = ROOT / "configs" / "accelsim"

QUEUE_OVERRIDES = (
    "-gpgpu_dram_partition_queues 64:64:64:64",
    "-gpgpu_frfcfs_dram_sched_queue_size 64",
    "-gpgpu_dram_return_queue_size 192",
)


@dataclass(frozen=True)
class CanonicalConfig:
    output: str
    title: str
    fragments: tuple[Path, ...]
    inline_overrides: tuple[str, ...] = QUEUE_OVERRIDES


CONFIGS = (
    CanonicalConfig(
        output="a100_hbm2e_1stack_8ch.gpgpusim.config",
        title="A100 1/5-stack style, 8 HBM2e channels, 22 SMs, 8 MiB L2",
        fragments=(FRAGMENT_DIR / "a100_1stack_8mb_l2.config",),
    ),
    CanonicalConfig(
        output="a100_hbm2e_full_40ch.gpgpusim.config",
        title="A100 full 5-stack style, 40 HBM2e channels, 108 SMs, 40 MiB L2",
        fragments=(FRAGMENT_DIR / "a100_5stack_hbm2e.config",),
    ),
    CanonicalConfig(
        output="h100_sxm_hbm3sid_1stack_16ch.gpgpusim.config",
        title="H100 SXM 1/5-stack style, 16 HBM3SID channels, 26 SMs, 10 MiB L2",
        fragments=(FRAGMENT_DIR / "h100_sxm_hbm3_1stack_16ch.config",),
    ),
    CanonicalConfig(
        output="h100_sxm_hbm3sid_full_80ch.gpgpusim.config",
        title="H100 SXM full 5-stack style, 80 HBM3SID channels, 132 SMs, 50 MiB L2",
        fragments=(FRAGMENT_DIR / "h100_sxm_hbm3_80ch.config",),
    ),
    CanonicalConfig(
        output="rtx5090_gddr7_1of8_8ch.gpgpusim.config",
        title="RTX 5090 1/8 style, 8 GDDR7 channels, 21 SMs, 12 MiB L2",
        fragments=(FRAGMENT_DIR / "rtx5090_gddr7_1of8_8ch.config",),
    ),
    CanonicalConfig(
        output="rtx5090_gddr7_full_64ch.gpgpusim.config",
        title="RTX 5090 full style, 64 GDDR7 channels, 170 SMs, 96 MiB L2",
        fragments=(FRAGMENT_DIR / "rtx5090_gddr7_full_64ch.config",),
    ),
)


def gpgpusim_option_key(line: str) -> str | None:
    stripped = line.strip()
    if not stripped or not stripped.startswith("-"):
        return None
    return stripped.split(maxsplit=1)[0]


def collapse_gpgpusim_config(lines: list[str]) -> list[str]:
    last_option_line: dict[str, int] = {}
    for index, line in enumerate(lines):
        key = gpgpusim_option_key(line)
        if key:
            last_option_line[key] = index

    return [
        line
        for index, line in enumerate(lines)
        if not (
            (key := gpgpusim_option_key(line))
            and last_option_line[key] != index
        )
    ]


def read_lines(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    if text and not text.endswith("\n"):
        lines.append("\n")
    return lines


def build_config(base_config: Path, spec: CanonicalConfig) -> str:
    lines = [
        "# Canonical AccelSim/GPGPU-Sim config for AccelSim + Ramulator2.\n",
        "# Generated by scripts/generate_canonical_accelsim_configs.py.\n",
        "# Duplicate GPGPU-Sim options are collapsed after applying fragments.\n",
        f"# title: {spec.title}\n",
        f"# base_config: {base_config}\n",
        "# use with: --gpgpusim-config <this file> --config-variant canonical\n",
        "\n",
    ]
    lines.extend(read_lines(base_config))
    lines.append("\n# Canonical architecture overrides\n")
    for fragment in spec.fragments:
        lines.append(f"# fragment: {fragment}\n")
        lines.extend(read_lines(fragment))
        lines.append("\n")
    if spec.inline_overrides:
        lines.append("# canonical queue defaults\n")
        lines.extend(f"{override}\n" for override in spec.inline_overrides)
    return "".join(collapse_gpgpusim_config(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-config", type=Path, default=DEFAULT_BASE)
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = parser.parse_args()

    base_config = args.base_config.resolve()
    out_dir = args.out_dir.resolve()
    if not base_config.exists():
        parser.error(f"missing base config: {base_config}")
    missing_fragments = [
        fragment
        for spec in CONFIGS
        for fragment in spec.fragments
        if not fragment.exists()
    ]
    if missing_fragments:
        parser.error(
            "missing fragment(s): "
            + ", ".join(str(path) for path in missing_fragments)
        )

    out_dir.mkdir(parents=True, exist_ok=True)
    for spec in CONFIGS:
        path = out_dir / spec.output
        path.write_text(build_config(base_config, spec), encoding="utf-8")
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
